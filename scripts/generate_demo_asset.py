"""Render the README terminal demo (assets/demo.svg) from REAL engine output.

Runs the deterministic workspace simulator (seed 7, 450 ticks, ~1 s) through the engine in a temporary
directory and records what the CLI-equivalent queries return: the active workspace, a visual patch query,
and two causal `why` traces. Storage/legacy figures in the footer are read from evals/latest_report.json
(produced by `python -m evals.benchmark_suite`); nothing is typed in by hand.

    python scripts/generate_demo_asset.py            # -> assets/demo.svg
"""

from __future__ import annotations

import io
import json
import shutil
import tempfile
import time
from pathlib import Path

from rich import box
from rich.console import Console, Group
from rich.markup import escape
from rich.panel import Panel
from rich.table import Table
from rich.terminal_theme import MONOKAI
from rich.text import Text
from rich.tree import Tree

from screengraph import __version__
from screengraph.capture.simulator import WorkspaceSimulator
from screengraph.config import Config
from screengraph.engine import ScreenGraph

ROOT = Path(__file__).resolve().parents[1]
def clip(s: str, n: int) -> str:
    s = s or ""
    return s if len(s) <= n else s[: n - 1] + "…"


CAT_STYLE = {"terminal": "green", "browser": "cyan", "ide": "blue", "dashboard": "magenta", "chat": "yellow"}


def prompt(cmd: str) -> Text:
    return Text.assemble(("❯ ", "bold green"), ("screengraph ", "bold white"), (cmd, "white"))


def why_tree(res: dict, target: str) -> Group:
    """Root cause, then one line per causal hop: relation, edge score S, evidence, destination window."""
    lines = [Text.assemble(("why ", "bold magenta"), (target, "bold white"), ("?  ", "bold magenta"),
                           (f"traced in {res['elapsed_ms']:.1f} ms", "dim"))]
    root = res["root_causes"][0]
    lines.append(Text.assemble(("  root cause ", "bold red"), (f"#{root['event_id']} ", "red"),
                               (f"[{root['app']}] ", CAT_STYLE.get(root["app_category"], "white")),
                               (clip(root["window_title"], 40), "white"), ("  ", ""),
                               (clip((root.get("snippet") or "").strip(), 44), "grey50")))
    for c in res["chain"][1:]:
        via = max(c["via"], key=lambda v: v["score"]) if c["via"] else None
        t = Text("    ↳ ", "grey50")
        if via:
            ev = [e.split(":", 1)[-1] for e in via["evidence"]]
            ev = clip(", ".join(e for e in ev if not e.startswith(("xmodal_cos", "energy"))), 26)
            t.append(f"{via['relation']:<27}", "bold yellow")
            t.append(f"S={via['score']:.2f}  ", "grey70")
            t.append(f"{ev:<27}", "grey50")
        app = f"[{c['app']}] "
        t.append(app, CAT_STYLE.get(c["app_category"], "white"))
        t.append(clip(c["window_title"], 104 - 6 - 27 - 8 - 27 - len(app)), "white")
        lines.append(t)
    return Group(*lines)


def main(out: Path = ROOT / "assets" / "demo.svg") -> Path:
    report = json.loads((ROOT / "evals" / "latest_report.json").read_text())
    tmp = Path(tempfile.mkdtemp(prefix="screengraph-demo-"))
    con = Console(record=True, width=108, force_terminal=True, color_system="truecolor", file=io.StringIO())
    try:
        sg = ScreenGraph(Config.ephemeral(tmp))
        sim = WorkspaceSimulator(seed=7)
        t0 = time.perf_counter()
        stored = ticks = 0
        for tk in sim.session():
            ticks += 1
            stored += sg.ingest_frame(tk.frame).stored
        wall = time.perf_counter() - t0

        con.print(Panel(Text.assemble(
            ("screengraph-os ", "bold magenta"), (f"v{__version__}", "magenta"),
            ("   zero-screenshot desktop memory · cross-app causal graph · MCP\n", "grey70"),
            ("deterministic simulator, seed 7 — real engine output, regenerated by scripts/generate_demo_asset.py", "grey50")),
            box=box.ROUNDED, border_style="magenta"))
        con.print(prompt("simulate"))
        con.print(Text.assemble(("  ", ""), (f"{ticks} window ticks", "white"), (" → ", "grey50"),
                                (f"{ticks - stored} dropped by the idle gate", "green"), (" · ", "grey50"),
                                (f"{stored} semantic events stored", "white"), (" · ", "grey50"),
                                (f"{wall:.2f} s", "grey70")))
        con.print()

        con.print(prompt("active-workspace"))
        ws = sg.active_workspace()
        t = Table(box=box.SIMPLE_HEAD, header_style="bold grey70", pad_edge=False, expand=False)
        for col, wd in (("mon", 3), ("app", 13), ("window", 30), ("viewport x,y w×h", 20), ("latest content", 30)):
            t.add_column(col, no_wrap=True, overflow="ellipsis", width=wd)
        for w in sorted(ws["windows"], key=lambda w: (w["bbox"]["monitor_id"], w["bbox"]["x"])):
            b = w["bbox"]
            t.add_row(str(b["monitor_id"]), Text(w["app"], CAT_STYLE.get(w["app_category"], "white")),
                      escape(w["title"] or ""), f"{b['x']},{b['y']} {b['width']}×{b['height']}",
                      escape((w["summary"][-1] if w["summary"] else "").strip()))
        con.print(t)

        q = "red memory spike chart in top-right quadrant"
        con.print(prompt(f'visual "{q}"'))
        hit = sg.visual_search(q, 1)[0]
        p = hit["patch"]
        sb = p["screen_bbox"]
        con.print(Text.assemble(("  #", "grey50"), (str(hit["event_id"]), "white"), ("  [Grafana] ", "magenta"),
                                (hit["window_title"], "white"), ("  MaxSim ", "grey50"), (f"{hit['maxsim']:.2f}", "white")))
        con.print(Text.assemble(("  patch ", "grey50"), (f"(row {p['row']}, col {p['col']}) {p['quadrant']}", "bold cyan"),
                                ("  screen ", "grey50"), (f"x={sb['x']} y={sb['y']} {sb['width']}×{sb['height']}", "white"),
                                (f" monitor {hit['monitor_id']}", "grey50")))
        con.print(Text.assemble(("  concepts ", "grey50"),
                                (" · ".join(k for k in p["visual_concepts"] if "_" not in k), "yellow"),
                                ("   (pixel-only frame: no text changed)", "grey50")))
        con.print()

        for target in ("k8s/payments-deployment.yaml", "db_pool.py"):
            con.print(prompt(f"why {target}"))
            con.print(why_tree(sg.why(target), target))
            con.print()

        audit = sg.privacy_audit()
        g = report["gate_and_storage"]
        sw = report.get("robustness_seed_sweep", {})
        rng = f" (seeds {sw['min']['projected_30d_mb']:.0f}–{sw['max']['projected_30d_mb']:.0f})" if sw else ""
        foot = Text.assemble(
            (f"{audit['disk'].get('image_magic_hits', 0)} image files on disk", "bold green"), ("  ·  ", "grey50"),
            (f"{audit['ram']['verification_failures']} wipe failures", "bold green"), ("  ·  ", "grey50"),
            (f"{g['projected_30d_8h_mb']:.1f} MB/30 d int8{rng}", "bold white"), ("  vs ", "grey50"),
            (f"{g['legacy_model_30d_8h_mb'] / 1000:.1f} GB", "red"), (" modelled video", "grey50"))
        con.print(Panel(foot, title="privacy & storage", title_align="left", box=box.ROUNDED, border_style="grey50"))
        sg.close()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    out.parent.mkdir(parents=True, exist_ok=True)
    con.save_svg(str(out), title="screengraph-os", theme=MONOKAI)
    return out


if __name__ == "__main__":
    print(main())
